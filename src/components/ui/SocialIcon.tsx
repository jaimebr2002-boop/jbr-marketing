import React from 'react';

interface SocialIconProps {
  href: string;
  label: string;
  children: React.ReactNode;
}

// Icon-only contact button with a real accessible label and a visible tooltip
// on hover/focus — never a bare text button ("LinkedIn", "Instagram"...).
export function SocialIcon({ href, label, children }: SocialIconProps) {
  const isExternal = href.startsWith('http');
  return (
    <a
      href={href}
      {...(isExternal ? { target: '_blank', rel: 'noopener noreferrer' } : {})}
      aria-label={label}
      title={label}
      className="group relative flex items-center justify-center w-10 h-10 rounded-full border border-white/15 text-white/70 hover:text-brand-accent hover:border-brand-accent/40 transition-colors duration-200 focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-brand-accent"
    >
      <span className="w-[18px] h-[18px]">{children}</span>
    </a>
  );
}

